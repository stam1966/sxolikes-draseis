	public static function import_plans() {
		global $wpdb;
		$year = SD_Data::active_year();
		if ( ! self::available_for( $year ) ) {
			return new WP_Error( 'sd', 'Η εισαγωγή αφορά μόνο το σχολικό έτος ' . self::YEAR . '.' );
		}
		if ( SD_Plans::plans( $year->id ) ) {
			return new WP_Error( 'sd', 'Υπάρχουν ήδη σχέδια για το έτος. Η εισαγωγή γίνεται μόνο σε κενό έτος.' );
		}
		$now = current_time( 'mysql' );
		foreach ( self::plans() as $p ) {
			$wpdb->insert(
				SD_Data::table( 'plans' ),
				array(
					'year_id'    => (int) $year->id,
					'code'       => $p['code'],
					'title'      => $p['title'],
					'axis'       => $p['axis'],
					'purpose'    => $p['purpose'],
					'need'       => $p['need'],
					'team_note'  => $p['team_note'],
					'created_at' => $now,
					'updated_at' => $now,
				)
			);
			$plan_id = (int) $wpdb->insert_id;
			foreach ( $p['goals'] as $gi => $g ) {
				$wpdb->insert(
					SD_Data::table( 'goals' ),
					array(
						'plan_id'     => $plan_id,
						'ord'         => $gi + 1,
						'title'       => $g['title'],
						'description' => $g['description'],
						'tools'       => $g['tools'],
						'ways'        => $g['ways'],
					)
				);
				$goal_id = (int) $wpdb->insert_id;
				foreach ( $g['actions'] as $ai => $a ) {
					$wpdb->insert(
						SD_Data::table( 'goal_actions' ),
						array(
							'goal_id'     => $goal_id,
							'kind'        => $a['kind'],
							'ord'         => $ai + 1,
							'description' => $a['description'],
							'start_date'  => $a['start'],
							'end_date'    => $a['end'],
							'criterion'   => $a['criterion'],
							'grades'      => $a['grades'],
						)
					);
				}
			}
		}
		return true;
	}
