		$blocks = array(
			array( 'p', SD_Frontend::school_name(), true ),
			array( 'title', 'Σχολικές Δράσεις · Οδηγός χρήστη' ),
		);
		if ( ! $all ) {
			$labels = array();
			foreach ( $mine as $k ) {
				if ( 'all' !== $k ) {
					$labels[] = self::AUDIENCES[ $k ];
				}
			}
			$blocks[] = array( 'p', 'Για: ' . implode( ' · ', $labels ) );
		}
		foreach ( self::sections() as $s ) {
			if ( ! in_array( $s[0], $mine, true ) ) {
				continue;
			}
			$blocks[] = array( 'h', $s[1] . ' (' . self::AUDIENCES[ $s[0] ] . ')' );
			foreach ( $s[2] as $sub ) {
				$blocks[] = array( 'p', $sub[0], true );
				foreach ( $sub[1] as $li ) {
					$blocks[] = array( 'p', '• ' . $li );
				}
			}
		}
		return $blocks;
	}
