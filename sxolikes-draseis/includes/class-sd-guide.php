	/** Τα κοινά που αφορούν τον τρέχοντα χρήστη. */
	public static function audiences_of_user() {
		$a = array( 'all', 'ekp' );
		$year = SD_Data::active_year();
		if ( current_user_can( SD_Roles::CAP_MANAGE ) ) {
			$a[] = 'syn';
		} elseif ( $year ) {
			foreach ( SD_Plans::plans( $year->id ) as $p ) {
				if ( (int) $p->coordinator_id === get_current_user_id() ) {
					$a[] = 'syn';
					break;
				}
			}
		}
		if ( current_user_can( SD_Roles::CAP_REVIEW ) ) {
			$a[] = 'review';
		}
		if ( current_user_can( SD_Roles::CAP_MANAGE ) ) {
			$a[] = 'manage';
		}
		return $a;
	}

	public static function render() {
		$mine = self::audiences_of_user();
		echo '<h2>Βοήθεια · Οδηγός χρήστη</h2>';
		$labels = array();
		foreach ( $mine as $k ) {
			if ( 'all' !== $k ) {
				$labels[] = self::AUDIENCES[ $k ];
			}
		}
		echo '<p class="sd-meta">Βλέπετε πρώτα ό,τι αφορά εσάς: <strong>' . esc_html( implode( ' · ', $labels ) ) . '</strong>. Τα υπόλοιπα είναι πιο κάτω, κλειστά.</p>';
		echo '<p class="sd-noprint"><a class="sd-button sd-small" href="' . esc_url( SD_Exports::url( 'odigos', 0 ) ) . '">Ο οδηγός μου σε Word</a> <a class="sd-button sd-small sd-quiet" href="' . esc_url( SD_Exports::url( 'odigos', 1 ) ) . '">Όλος ο οδηγός σε Word</a></p>';

		$secs   = self::sections();
		$others = array();
		echo '<nav class="sd-card sd-toc" aria-label="Περιεχόμενα"><strong>Περιεχόμενα</strong><ol>';
		foreach ( $secs as $id => $s ) {
			if ( in_array( $s[0], $mine, true ) ) {
				echo '<li><a href="#odigos-' . esc_attr( $id ) . '">' . esc_html( $s[1] ) . '</a></li>';
			} else {
				$others[ $id ] = $s;
			}
		}
		echo '</ol></nav>';
		foreach ( $secs as $id => $s ) {
			if ( in_array( $s[0], $mine, true ) ) {
				self::section_html( $id, $s, false );
			}
		}
		if ( $others ) {
			echo '<h3 class="sd-guide-others">Για τους άλλους ρόλους</h3>';
			foreach ( $others as $id => $s ) {
				self::section_html( $id, $s, true );
			}
		}
	}

	private static function section_html( $id, $s, $closed ) {
		$open  = $closed ? '<details class="sd-card sd-guide" id="odigos-' . esc_attr( $id ) . '"><summary>' : '<section class="sd-card sd-guide" id="odigos-' . esc_attr( $id ) . '"><h3>';
		$close = $closed ? '</summary>' : '</h3>';
		echo $open . esc_html( $s[1] ) . ' <span class="sd-badge">' . esc_html( self::AUDIENCES[ $s[0] ] ) . '</span>' . $close; // phpcs:ignore WordPress.Security.EscapeOutput
		foreach ( $s[2] as $sub ) {
			echo '<h4>' . esc_html( $sub[0] ) . '</h4><ul>';
			foreach ( $sub[1] as $li ) {
				echo '<li>' . esc_html( $li ) . '</li>';
			}
			echo '</ul>';
		}
		echo $closed ? '</details>' : '</section>';
	}

