	public static function axis_label( $axis ) {
		return isset( self::AXES[ (int) $axis ] ) ? self::AXES[ (int) $axis ][0] : '';
	}

	public static function function_label( $axis ) {
		return isset( self::AXES[ (int) $axis ] ) ? self::FUNCTIONS[ self::AXES[ (int) $axis ][1] ] : '';
	}

	/** Δείκτες ενός άξονα. */
	public static function indicators_of( $axis ) {
		$out = array();
		foreach ( self::INDICATORS as $id => $label ) {
			if ( (int) strtok( $id, '.' ) === (int) $axis ) {
				$out[ $id ] = $label;
			}
		}
		return $out;
	}

	/** Μήκος κειμένου όπως το μετρά μια φόρμα: κάθε αλλαγή γραμμής μετρά ένας χαρακτήρας. */
	public static function length( $text ) {
		return mb_strlen( str_replace( "\r\n", "\n", (string) $text ), 'UTF-8' );
	}
